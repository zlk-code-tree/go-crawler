-- 1. 快手订单表
CREATE TABLE IF NOT EXISTS `kuaishou_orders` (
    `id`                    BIGINT(20) NOT NULL AUTO_INCREMENT COMMENT '主键ID',
    `shop_name`             VARCHAR(255) DEFAULT '' COMMENT '店铺名称',
    `main_order_no`         VARCHAR(100) DEFAULT '' COMMENT '主订单编号',
    `sub_order_no`          VARCHAR(100) DEFAULT '' COMMENT '子订单编号',
    `product_name`          VARCHAR(500) DEFAULT '' COMMENT '选购商品',
    `product_spec`          VARCHAR(255) DEFAULT '' COMMENT '商品规格',
    `product_num`           INT(11) DEFAULT 1 COMMENT '商品数量',
    `product_id`            VARCHAR(100) DEFAULT '' COMMENT '商品ID',
    `seller_code`           VARCHAR(100) DEFAULT '' COMMENT '商家编码',
    `product_price`         DECIMAL(12,2) DEFAULT 0.00 COMMENT '商品单价',
    `order_pay_amount`      DECIMAL(12,2) DEFAULT 0.00 COMMENT '订单应付金额',
    `shipping_fee`          DECIMAL(12,2) DEFAULT 0.00 COMMENT '运费',
    `total_discount`        DECIMAL(12,2) DEFAULT 0.00 COMMENT '优惠总金额',
    `platform_discount`     DECIMAL(12,2) DEFAULT 0.00 COMMENT '平台优惠',
    `seller_discount`       DECIMAL(12,2) DEFAULT 0.00 COMMENT '商家优惠',
    `talent_discount`       DECIMAL(12,2) DEFAULT 0.00 COMMENT '达人优惠',
    `seller_change_price`   DECIMAL(12,2) DEFAULT 0.00 COMMENT '商家改价',
    `pay_discount`          DECIMAL(12,2) DEFAULT 0.00 COMMENT '支付优惠',
    `red_deduction`         DECIMAL(12,2) DEFAULT 0.00 COMMENT '红包抵扣',
    `pay_type`              VARCHAR(50) DEFAULT '' COMMENT '支付方式',
    `service_fee`           DECIMAL(12,2) DEFAULT 0.00 COMMENT '手续费',
    `receiver_name`         VARCHAR(100) DEFAULT '' COMMENT '收件人',
    `receiver_phone`        VARCHAR(50) DEFAULT '' COMMENT '收件人手机号',
    `province`              VARCHAR(50) DEFAULT '' COMMENT '省',
    `city`                  VARCHAR(50) DEFAULT '' COMMENT '市',
    `district`              VARCHAR(255) DEFAULT '' COMMENT '区',
    `street`                VARCHAR(255) DEFAULT '' COMMENT '街道',
    `address_detail`        VARCHAR(500) DEFAULT '' COMMENT '详细地址',
    `is_address_changed`    VARCHAR(10) DEFAULT '' COMMENT '是否修改过地址',
    `address_change_time`   VARCHAR(100) DEFAULT '' COMMENT '地址修改时段',
    `buyer_note`            VARCHAR(500) DEFAULT '' COMMENT '买家留言',
    `order_submit_time`     DATETIME DEFAULT NULL COMMENT '订单提交时间',
    `flag_color`            VARCHAR(50) DEFAULT '' COMMENT '旗帜颜色',
    `seller_note`           VARCHAR(500) DEFAULT '' COMMENT '商家备注',
    `order_finish_time`     DATETIME DEFAULT NULL COMMENT '订单完成时间',
    `pay_finish_time`       DATETIME DEFAULT NULL COMMENT '支付完成时间',
    `app_channel`           VARCHAR(50) DEFAULT '' COMMENT 'APP渠道',
    `flow_source`           VARCHAR(50) DEFAULT '' COMMENT '流量来源',
    `order_status`          VARCHAR(50) DEFAULT '' COMMENT '订单状态',
    `promise_send_time`     DATETIME DEFAULT NULL COMMENT '承诺发货时间',
    `order_type`            VARCHAR(50) DEFAULT '' COMMENT '订单类型',
    `luban_page_id`         VARCHAR(100) DEFAULT '' COMMENT '鲁班落地页ID',
    `talent_id`             VARCHAR(100) DEFAULT '' COMMENT '达人ID',
    `talent_name`           VARCHAR(100) DEFAULT '' COMMENT '达人昵称',
    `store_id`              VARCHAR(100) DEFAULT '' COMMENT '所属门店ID',
    `after_sale_status`     VARCHAR(50) DEFAULT '' COMMENT '售后状态',
    `cancel_reason`         VARCHAR(255) DEFAULT '' COMMENT '取消原因',
    `appoint_send_time`     DATETIME DEFAULT NULL COMMENT '预约发货时间',
    `warehouse_id`          VARCHAR(100) DEFAULT '' COMMENT '仓库ID',
    `warehouse_name`        VARCHAR(100) DEFAULT '' COMMENT '仓库名称',
    `is_safe_buy`           VARCHAR(10) DEFAULT '' COMMENT '是否安心购',
    `ad_channel`            VARCHAR(50) DEFAULT '' COMMENT '广告渠道',
    `flow_type`             VARCHAR(50) DEFAULT '' COMMENT '流量类型',
    `flow_format`           VARCHAR(50) DEFAULT '' COMMENT '流量体裁',
    `flow_channel`          VARCHAR(50) DEFAULT '' COMMENT '流量渠道',
    `send_user`             VARCHAR(50) DEFAULT '' COMMENT '发货主体',
    `send_user_detail`      VARCHAR(100) DEFAULT '' COMMENT '发货主体明细',
    `send_time`             DATETIME DEFAULT NULL COMMENT '发货时间',
    `reduce_discount`       DECIMAL(12,2) DEFAULT 0.00 COMMENT '降价类优惠',
    `platform_real_discount` DECIMAL(12,2) DEFAULT 0.00 COMMENT '平台实际承担优惠金额',
    `seller_real_discount`  DECIMAL(12,2) DEFAULT 0.00 COMMENT '商家实际承担优惠金额',
    `talent_real_discount`  DECIMAL(12,2) DEFAULT 0.00 COMMENT '达人实际承担优惠金额',
    `expect_arrive_time`    DATETIME DEFAULT NULL COMMENT '预计送达时间',
    PRIMARY KEY (`id`),
    INDEX `idx_sub_order_no` (`sub_order_no`),
    INDEX `idx_main_order_no` (`main_order_no`),
    INDEX `idx_shop_name` (`shop_name`),
    INDEX `idx_order_status` (`order_status`),
    INDEX `idx_pay_finish_time` (`pay_finish_time`),
    INDEX `idx_talent_name` (`talent_name`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='快手平台订单表';


