-- 精选联盟订单表
CREATE TABLE IF NOT EXISTS `alliance_orders` (
  `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '主键',
  `platform` VARCHAR(50) NOT NULL DEFAULT 'douyin' COMMENT '平台',
  `order_id` VARCHAR(100) NOT NULL DEFAULT '' COMMENT '联盟订单号',
  `product_id` VARCHAR(100) NOT NULL DEFAULT '' COMMENT '商品ID',
  `product_name` VARCHAR(500) NOT NULL DEFAULT '' COMMENT '商品名称',
  `product_img` VARCHAR(500) NOT NULL DEFAULT '' COMMENT '商品图片',
  `product_num` INT NOT NULL DEFAULT 0 COMMENT '商品数量',
  `product_price` DECIMAL(12,2) NOT NULL DEFAULT 0.00 COMMENT '商品单价(元)',
  `pay_amount` DECIMAL(12,2) NOT NULL DEFAULT 0.00 COMMENT '支付金额(元)',
  `commission_rate` DECIMAL(8,2) NOT NULL DEFAULT 0.00 COMMENT '佣金比例(%)',
  `commission` DECIMAL(12,2) NOT NULL DEFAULT 0.00 COMMENT '预计佣金(元)',
  `order_status` INT NOT NULL DEFAULT 0 COMMENT '订单状态',
  `order_status_desc` VARCHAR(100) NOT NULL DEFAULT '' COMMENT '订单状态描述',
  `author_id` VARCHAR(100) NOT NULL DEFAULT '' COMMENT '达人ID',
  `author_name` VARCHAR(200) NOT NULL DEFAULT '' COMMENT '达人名称',
  `shop_name` VARCHAR(200) NOT NULL DEFAULT '' COMMENT '店铺名称',
  `pay_time` DATETIME DEFAULT NULL COMMENT '支付时间',
  `create_time` DATETIME DEFAULT NULL COMMENT '下单时间',
  `finish_time` DATETIME DEFAULT NULL COMMENT '完成时间',
  `after_sale_status` INT NOT NULL DEFAULT 0 COMMENT '售后状态',
  `created_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  `updated_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_platform_order` (`platform`, `order_id`),
  INDEX `idx_author_id` (`author_id`),
  INDEX `idx_pay_time` (`pay_time`),
  INDEX `idx_create_time` (`create_time`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='精选联盟订单表';
